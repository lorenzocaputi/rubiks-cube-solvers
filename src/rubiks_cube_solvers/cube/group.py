"""Order of the cube group, from the counting formula and by Schreier-Sims."""

from __future__ import annotations

from collections.abc import Sequence
from math import factorial

Perm = tuple[int, ...]


def cube_group_order() -> int:
    """8! 3^8 12! 2^12 / 12: corner twists sum to 0 mod 3, edge flips to 0 mod 2,
    and the corner and edge permutations have equal parity."""
    return factorial(8) * 3**8 * factorial(12) * 2**12 // (3 * 2 * 2)


def _compose(p: Perm, q: Perm) -> Perm:
    """Apply p, then q."""
    return tuple(q[x] for x in p)


def _inverse(p: Perm) -> Perm:
    inv = [0] * len(p)
    for i, x in enumerate(p):
        inv[x] = i
    return tuple(inv)


def schreier_sims_order(generators: Sequence[Sequence[int]]) -> int:
    """Order of the permutation group generated by ``generators`` (Holt's SCHREIERSIMS)."""
    gens = [tuple(g) for g in generators]
    n = len(gens[0])
    identity = tuple(range(n))
    gens = [g for g in gens if g != identity]
    base: list[int] = []
    strong: list[list[Perm]] = []  # strong[i]: generators fixing base[:i]

    def moved_point(p: Perm) -> int:
        return next(x for x in range(n) if p[x] != x)

    for g in gens:
        if all(g[b] == b for b in base):
            base.append(moved_point(g))
            strong.append([])
        for i in range(len(base)):
            if all(g[b] == b for b in base[:i]):
                strong[i].append(g)

    def transversal(i: int) -> dict[int, Perm]:
        reps = {base[i]: identity}
        frontier = [base[i]]
        while frontier:
            nxt = []
            for beta in frontier:
                for s in strong[i]:
                    image = s[beta]
                    if image not in reps:
                        reps[image] = _compose(reps[beta], s)
                        nxt.append(image)
            frontier = nxt
        return reps

    transversals: list[dict[int, Perm]] = [transversal(i) for i in range(len(base))]

    def strip(h: Perm, start: int) -> tuple[Perm, int]:
        for level in range(start, len(base)):
            beta = h[base[level]]
            if beta not in transversals[level]:
                return h, level
            h = _compose(h, _inverse(transversals[level][beta]))
        return h, len(base)

    i = len(base) - 1
    while i >= 0:
        transversals[i] = transversal(i)
        restart = False
        for beta, u in list(transversals[i].items()):
            for s in strong[i]:
                image = s[beta]
                schreier = _compose(_compose(u, s), _inverse(transversals[i][image]))
                if schreier == identity:
                    continue
                h, j = strip(schreier, i + 1)
                if h == identity:
                    continue
                if j == len(base):
                    base.append(moved_point(h))
                    strong.append([])
                    transversals.append({})
                for level in range(i + 1, j + 1):
                    strong[level].append(h)
                    transversals[level] = transversal(level)
                i = j
                restart = True
                break
            if restart:
                break
        if not restart:
            i -= 1

    order = 1
    for t in transversals:
        order *= len(t)
    return order
